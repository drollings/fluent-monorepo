//! Reference-overlap parity matrix: every construct the reference scripting
//! layer covers, with the engine symbol that implements it and the standing
//! of the overlap (`match`, `correct` for deliberate pinned divergences,
//! `refuse` with the exact reason). Rows that refuse carry an executable
//! probe plus the exact refusal string so the matrix is checked, not read.
//!
//! Citations name the reference symbol (`register_builtins` entry, `Runtime`
//! method, `ast` node) and the engine symbol (`TaBridge`, `builtins_core`
//! arm, `eval` rule) side by side. Anything outside the matrix refuses with
//! a reason instead of miscomputing.

/// Standing of one overlap construct.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum ParityVerdict {
    /// Identical observable behavior on the overlap suite.
    Match,
    /// Deliberate pinned divergence, with the reason on the row.
    Correct,
    /// Refused headlessly with the exact reason on the row.
    Refuse,
}

/// One matrix row: a construct, both-side citations, its standing, and —
/// for refusals — the probe script plus the exact refusal string.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct EguiParityRow {
    /// Construct name (`ta.sma`, `if/else`, `division (/)`, ...).
    pub construct: &'static str,
    /// Reference symbol (`register_builtins` entry, `Runtime` method, `ast` node).
    pub egui: &'static str,
    /// Engine symbol (`TaBridge` entry, `builtins_core` arm, `eval` rule).
    pub protopyne: &'static str,
    /// Standing of the overlap.
    pub verdict: ParityVerdict,
    /// Reason for `Correct`/`Refuse`; empty for `Match`.
    pub reason: &'static str,
    /// Probe script executed by the matrix tests, if any.
    pub probe: Option<&'static str>,
    /// Exact refusal message (without the `pine evaluation refused` prefix).
    pub refusal: Option<&'static str>,
}

